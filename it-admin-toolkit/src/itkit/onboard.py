"""Turn an HR new-hire list (CSV) into ready-to-run account scripts.

Input columns:  first_name, last_name, department, [title], [start_date]
Output:
  * accounts.csv     - usernames, e-mail addresses, one-time passwords
  * create_users.ps1 - Active Directory (New-ADUser) script, or
  * create_users.sh  - Linux useradd script

Nothing is executed; an admin reviews the generated script first.
"""
from __future__ import annotations

import csv
import re
import secrets
import string
import unicodedata
from dataclasses import dataclass
from pathlib import Path

# German and Greek-style transliterations that NFKD alone gets wrong
TRANSLIT = {"ä": "ae", "ö": "oe", "ü": "ue", "ß": "ss", "Ä": "Ae", "Ö": "Oe", "Ü": "Ue"}

REQUIRED = ("first_name", "last_name", "department")


@dataclass
class Account:
    first_name: str
    last_name: str
    department: str
    title: str
    username: str
    email: str
    password: str
    start_date: str = ""


def ascii_slug(text: str) -> str:
    for k, v in TRANSLIT.items():
        text = text.replace(k, v)
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z]", "", text.lower())


def make_username(first: str, last: str, taken: set[str], max_len: int = 20) -> str:
    """first.last, shortened and de-duplicated: anna.mueller, anna.mueller2, ..."""
    base = f"{ascii_slug(first)}.{ascii_slug(last)}".strip(".")[:max_len]
    if not base:
        raise ValueError(f"cannot build username from {first!r} {last!r}")
    name, n = base, 2
    while name in taken:
        suffix = str(n)
        name = base[: max_len - len(suffix)] + suffix
        n += 1
    taken.add(name)
    return name


def make_password(length: int = 16) -> str:
    """Cryptographically random password meeting typical AD complexity rules."""
    if length < 12:
        raise ValueError("password length must be at least 12")
    pools = [string.ascii_lowercase, string.ascii_uppercase, string.digits, "!#$%&*+-=?@"]
    # avoid look-alike characters people mistype from a printout
    pools = ["".join(c for c in p if c not in "Il1O0") for p in pools]
    chars = [secrets.choice(p) for p in pools]
    everything = "".join(pools)
    chars += [secrets.choice(everything) for _ in range(length - len(chars))]
    secrets.SystemRandom().shuffle(chars)
    return "".join(chars)


def read_hires(path: Path) -> list[dict]:
    with open(path, newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        header = [h.strip().lower() for h in reader.fieldnames or []]
        missing = [c for c in REQUIRED if c not in header]
        if missing:
            raise ValueError(f"missing column(s): {', '.join(missing)}")
        rows = []
        for i, raw in enumerate(reader, start=2):
            row = {k.strip().lower(): (v or "").strip() for k, v in raw.items() if k}
            if not row["first_name"] or not row["last_name"]:
                raise ValueError(f"line {i}: first_name and last_name are required")
            rows.append(row)
        return rows


def build_accounts(rows: list[dict], domain: str, existing: set[str] | None = None) -> list[Account]:
    taken = set(existing or ())
    accounts = []
    for r in rows:
        user = make_username(r["first_name"], r["last_name"], taken)
        accounts.append(Account(
            first_name=r["first_name"], last_name=r["last_name"],
            department=r["department"], title=r.get("title", ""),
            username=user, email=f"{user}@{domain}", password=make_password(),
            start_date=r.get("start_date", ""),
        ))
    return accounts


def _ps(s: str) -> str:
    """Quote for a single-quoted PowerShell string."""
    return "'" + s.replace("'", "''") + "'"


def powershell_script(accounts: list[Account], ou: str) -> str:
    lines = [
        "# Generated by itkit onboard - review before running.",
        "#Requires -Modules ActiveDirectory",
        "$ErrorActionPreference = 'Stop'",
        "",
    ]
    for a in accounts:
        lines += [
            f"# {a.first_name} {a.last_name} ({a.department})",
            "New-ADUser `",
            f"  -Name {_ps(a.first_name + ' ' + a.last_name)} `",
            f"  -GivenName {_ps(a.first_name)} -Surname {_ps(a.last_name)} `",
            f"  -SamAccountName {_ps(a.username)} -UserPrincipalName {_ps(a.email)} `",
            f"  -EmailAddress {_ps(a.email)} -Department {_ps(a.department)} -Title {_ps(a.title)} `",
            f"  -Path {_ps(ou)} `",
            f"  -AccountPassword (ConvertTo-SecureString {_ps(a.password)} -AsPlainText -Force) `",
            "  -ChangePasswordAtLogon $true -Enabled $true",
            "",
        ]
    return "\n".join(lines)


def bash_script(accounts: list[Account]) -> str:
    lines = ["#!/usr/bin/env bash", "# Generated by itkit onboard - review before running.", "set -euo pipefail", ""]
    for a in accounts:
        group = ascii_slug(a.department) or "staff"
        comment = f"{a.first_name} {a.last_name}".replace("'", "")
        lines += [
            f"getent group {group} >/dev/null || groupadd {group}",
            f"useradd -m -s /bin/bash -G {group} -c '{comment}' {a.username}",
            f"echo '{a.username}:{a.password}' | chpasswd",
            f"chage -d 0 {a.username}   # force password change at first login",
            "",
        ]
    return "\n".join(lines)


def write_outputs(accounts: list[Account], out_dir: Path, target: str, ou: str) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = out_dir / "accounts.csv"
    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["username", "email", "first_name", "last_name", "department", "title", "start_date", "initial_password"])
        for a in accounts:
            w.writerow([a.username, a.email, a.first_name, a.last_name, a.department, a.title, a.start_date, a.password])
    if target == "ad":
        script = out_dir / "create_users.ps1"
        script.write_text(powershell_script(accounts, ou), encoding="utf-8")
    else:
        script = out_dir / "create_users.sh"
        script.write_text(bash_script(accounts), encoding="utf-8")
        script.chmod(0o750)
    return [csv_path, script]
